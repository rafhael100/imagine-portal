<?php

declare(strict_types=1);

// F89: synthetic tenant+membership security event audit tests in disposable
// local PostgreSQL. No real audit authority or external anti-rollback witness.
if (PHP_SAPI !== 'cli' || getenv('APP_ENV') !== 'testing'
    || getenv('PORTAL_F89_PG_LAB') !== '1'
    || getenv('PGHOST') !== '127.0.0.1'
    || getenv('PGPORT') !== '5432'
    || getenv('PGDATABASE') !== 'portal_identity_lab') {
    throw new RuntimeException('F89 refuses non-test PostgreSQL connections.');
}
$adminPassword = getenv('F66_PG_ADMIN_PASSWORD');
$readerPassword = getenv('F89_PG_READER_PASSWORD');
if (!is_string($adminPassword) || strlen($adminPassword) < 12
    || !is_string($readerPassword) || strlen($readerPassword) < 12) {
    throw new RuntimeException('F89 ephemeral database roles are required.');
}
$db = static fn(string $username, string $password): PDO => new PDO(
    'pgsql:host=127.0.0.1;port=5432;dbname=portal_identity_lab;connect_timeout=3',
    $username, $password,
    [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
     PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
     PDO::ATTR_EMULATE_PREPARES => false]
);
$admin = $db('postgres', $adminPassword);
$reader = $db('portal_f89_reader', $readerPassword);
$checks = 0;
$check = static function(bool $valid, string $reason) use (&$checks): void {
    if (!$valid) {
        throw new RuntimeException('F89 FAIL '.$reason);
    }
    ++$checks;
};
$reject = static function(callable $action, string $sqlState, string $reason) use ($check): void {
    try {
        $action();
        $check(false, $reason.' unexpectedly succeeded');
    } catch (PDOException $e) {
        $check($e->getCode() === $sqlState,
            $reason.' expected '.$sqlState.', got '.$e->getCode());
    }
};

$orgA = 'a1111111-1111-4111-8111-111111111111';
$orgB = 'a2222222-2222-4222-8222-222222222222';
$person = 'a3333333-3333-4333-8333-333333333333';
$membership = 'a4444444-4444-4444-8444-444444444444';
$event = 'a5555555-5555-4555-8555-555555555555';
$evidence = hash('sha256', 'f89-synthetic-mfa-reset-evidence-without-PII');
$orgInsert = $admin->prepare(
    "INSERT INTO portal_organizations
       (id,reference,display_name,status,security_revision,created_at,updated_at)
     VALUES(?,?,?,'active',1,now(),now())"
);
$orgInsert->execute([$orgA,'f89-tenant-a','Synthetic A']);
$orgInsert->execute([$orgB,'f89-tenant-b','Synthetic B']);
$admin->prepare(
    "INSERT INTO portal_identities
       (id,email_normalized,status,security_revision,created_at,updated_at)
     VALUES(?,?,'active',1,now(),now())"
)->execute([$person,'f89@example.invalid']);
$admin->prepare(
    "INSERT INTO portal_memberships
       (id,identity_id,organization_id,role,status,membership_revision,created_at,updated_at)
     VALUES(?,?,?,'member','active',1,now(),now())"
)->execute([$membership,$person,$orgA]);

$insert = $admin->prepare(
    'INSERT INTO portal_security_events
       (event_id,organization_id,identity_id,event_code,evidence_sha256,security_revision)
     VALUES(?,?,?,?,?,?)'
);
$insert->execute([$event,$orgA,$person,'mfa.reset',$evidence,1]);
$check((int)$admin->query('SELECT count(*) FROM portal_security_events')->fetchColumn() === 1,
    'one event persisted by disposable fixture administrator');
$record = $admin->query(
    'SELECT sequence,event_id,organization_id,identity_id,event_code,evidence_sha256
       FROM portal_security_events'
)->fetch();
$check((int)$record['sequence'] > 0 && $record['evidence_sha256'] === $evidence,
    'autogenerated sequence, sanitized evidence hash');
$check($record['organization_id'] === $orgA && $record['identity_id'] === $person,
    'event belongs to exact identity/tenant pair');
$check(!array_key_exists('email', $record) && !array_key_exists('password', $record)
    && !array_key_exists('bearer', $record), 'select projection excludes PII and bearer');

$flags = $admin->query(
    "SELECT relrowsecurity,relforcerowsecurity FROM pg_class
       WHERE oid='public.portal_security_events'::regclass"
)->fetch();
$check(in_array($flags['relrowsecurity'],[true,'t','1'],true)
    && in_array($flags['relforcerowsecurity'],[true,'t','1'],true), 'FORCE RLS remains enabled');
$check((int)$admin->query(
    "SELECT count(*) FROM pg_policies WHERE tablename='portal_security_events'"
)->fetchColumn() === 0, 'zero application RLS policies');
$check((int)$reader->query('SELECT count(*) FROM portal_security_events')->fetchColumn() === 0,
    'role with accidental SELECT grant sees zero rows');
$check($reader->exec("UPDATE portal_security_events SET security_revision=2") === 0,
    'role with accidental UPDATE grant cannot see rows to modify');
$check($reader->exec('DELETE FROM portal_security_events') === 0,
    'role with accidental DELETE grant cannot see rows to remove');

$readerInsert = $reader->prepare(
    'INSERT INTO portal_security_events
       (event_id,organization_id,event_code,evidence_sha256,security_revision)
     VALUES(?,?,?,?,?)'
);
$reject(static fn()=> $readerInsert->execute([
    'a6666666-6666-4666-8666-666666666666',$orgA,
    'organization.suspended',$evidence,2
]),'42501','ordinary role cannot insert event even with direct GRANT');

$reject(static fn()=> $admin->exec(
    "UPDATE portal_security_events SET event_code='identity.revoked'"
),'42501','admin cannot mutate recorded event');
$reject(static fn()=> $admin->exec(
    'DELETE FROM portal_security_events'
),'42501','admin cannot delete recorded event');
$reject(static fn()=> $admin->exec(
    'TRUNCATE TABLE portal_security_events RESTART IDENTITY'
),'42501','admin cannot truncate audit history');

$reject(static fn()=> $admin->prepare(
    'INSERT INTO portal_security_events
       (event_id,organization_id,identity_id,event_code,evidence_sha256,security_revision)
     VALUES(?,?,?,?,?,?)'
)->execute(['a7777777-7777-4777-8777-777777777777',$orgB,$person,
    'membership.revoked',$evidence,1]),'23503',
    'identity belonging only to org A cannot be logged as member of org B');
$reject(static fn()=> $insert->execute([
    'a8888888-8888-4888-8888-888888888888',$orgA,$person,'grant.issued',$evidence,1
]),'23514','unsupported event code denied');
$reject(static fn()=> $insert->execute([
    'a9999999-9999-4999-8999-999999999999',$orgA,$person,'grant.revoked','not-a-sha256',1
]),'23514','invalid evidence hash denied');
$reject(static fn()=> $insert->execute([
    'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',$orgA,$person,'grant.revoked',$evidence,0
]),'23514','non-positive revision denied');
$reject(static fn()=> $insert->execute([
    $event,$orgA,$person,'mfa.reset',$evidence,1
]),'23505','duplicate event ID denied');

$check((int)$admin->query('SELECT count(*) FROM portal_security_events')->fetchColumn() === 1,
    'failed operations did not mutate audit history');
$check((int)$admin->query(
    "SELECT count(*) FROM pg_trigger WHERE tgrelid='public.portal_security_events'::regclass
       AND NOT tgisinternal"
)->fetchColumn() === 2, 'row-mutation and truncate triggers installed');
$check((int)$admin->query(
    "SELECT count(*) FROM information_schema.columns
       WHERE table_schema='public' AND table_name='portal_security_events'
         AND column_name IN ('email','ip_address','password','bearer','mfa_secret')"
)->fetchColumn() === 0, 'audit table cannot store direct identity secrets in reserved columns');

echo 'PASS PORTAL-F89 '.$checks .
    " PostgreSQL synthetic append-only audit and cross-tenant denial checks.\n";
