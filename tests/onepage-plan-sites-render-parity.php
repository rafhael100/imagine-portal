<?php

declare(strict_types=1);

// Candidate source + separate editorial copy exercised against the exact
// Sites renderer. No Portal/Sites databases, HTTP, customer files or provider.
$root = dirname(__DIR__);
$sites = $root.'/.pinned-sites';
if (PHP_SAPI !== 'cli' || getenv('SITES_PINNED_CANDIDATE_CI') !== '1' ||
    !is_dir($sites) || is_link($sites)) throw new RuntimeException('Pinned Sites required');

spl_autoload_register(static function (string $class) use ($sites): void {
    $prefix = 'Imagine\\Sites\\';
    if (str_starts_with($class,$prefix)) {
        $path = $sites.'/src/'.str_replace('\\','/',substr($class,strlen($prefix))).'.php';
        if (is_file($path)) require_once $path;
    }
});

require $root.'/apps/portal/app/Domain/SitesIntegration/SiteContractSnapshot.php';
require $root.'/apps/portal/app/Domain/SitesIntegration/OnepageBriefSnapshotCandidateEncoder.php';
require $root.'/apps/portal/app/Domain/SitesIntegration/OnepageRenderPlanCandidateEncoder.php';

use App\Domain\SitesIntegration\SiteContractSnapshot;
use App\Domain\SitesIntegration\OnepageBriefSnapshotCandidateEncoder as Snapshot;
use App\Domain\SitesIntegration\OnepageRenderPlanCandidateEncoder as Plan;
use Imagine\Sites\Production\LocalSiteRendering;
use Imagine\Sites\Production\BriefRenderPlanInput;
use Imagine\Sites\Production\BriefRenderProvenance;

$checks = 0;
$ok = static function(bool $condition,string $label) use (&$checks): void {
    if (!$condition) throw new RuntimeException('Paired candidate render failure: '.$label);
    ++$checks;
};
$examples = $sites.'/contracts/portal-sites/candidates/brief-production-v1/examples';
$source = file_get_contents($examples.'/onepage-brief.synthetic.json');
$editorial = file_get_contents($examples.'/render-input.synthetic.json');
$sample = json_decode(file_get_contents($examples.'/brief-snapshot.synthetic.json'),true,8,JSON_THROW_ON_ERROR);
$reference = json_decode(file_get_contents($examples.'/brief-render-plan.synthetic.json'),true,8,JSON_THROW_ON_ERROR);
$ok(is_string($source) && is_string($editorial) &&
    is_array($sample) && is_array($reference) &&
    str_ends_with($source,"\n") && str_ends_with($editorial,"\n"),
    'original pinned sample bytes and exact selectors are present');
$contract = new SiteContractSnapshot(
    $sample['tenantRef'],$sample['orderRef'],$sample['contractRef'],
    $sample['contractRevision'],$sample['productCode'],
);
$selector = [
    'siteRef'=>$sample['siteRef'],'snapshotRef'=>$sample['snapshotRef'],
    'operationId'=>$sample['operationId'],'idempotencyKey'=>$sample['idempotencyKey'],
    'sourceVersion'=>$sample['sourceVersion'],
    'expectedBriefRevision'=>$sample['expectedBriefRevision'],
    'payloadRef'=>$sample['payload']['payloadRef'],
];
$snapshot = Snapshot::build($contract,$selector,$source);
$renderSelection = [
    'operationId'=>$reference['operationId'],
    'idempotencyKey'=>$reference['idempotencyKey'],
    'releaseRef'=>$reference['releaseRef'],
    'renderInputRef'=>$reference['renderInput']['payloadRef'],
];
$artifact = LocalSiteRendering::render($editorial);
$ok($artifact->digest === hash('sha256',$artifact->html) &&
    $artifact->sizeBytes === strlen($artifact->html),
    'actual Sites renderer produces a byte-exact SHA and length');
$plan = Plan::build($snapshot,$editorial,$renderSelection,[
    'sha256'=>$artifact->digest,'sizeBytes'=>$artifact->sizeBytes,
]);
$parsed = BriefRenderPlanInput::fromJson($plan['planBytes']);
$ok($parsed->tenantRef===$sample['tenantRef'] &&
    $parsed->siteRef===$sample['siteRef'] &&
    $parsed->snapshotRef===$sample['snapshotRef'] &&
    $parsed->briefRevision===1 &&
    $parsed->manifestSha256===$snapshot['manifestSha256'],
    'Sites plan parser accepts exact snapshot/revision manifest from Portal candidate');
$ok($parsed->planSha256===$plan['planSha256'] &&
    $parsed->renderInputSha256===$plan['editorialSha256'] &&
    $parsed->expectedArtifactDigest===$artifact->digest &&
    $parsed->expectedArtifactSizeBytes===$artifact->sizeBytes,
    'metadata binds editorial bytes and actual renderer output');

$rendered = BriefRenderProvenance::render(
    $plan['planBytes'],$snapshot['manifestBytes'],$snapshot['sourceBytes'],$editorial,
);
$ok($rendered['artifact']->html === $artifact->html &&
    $rendered['artifact']->digest === $artifact->digest &&
    $rendered['artifact']->sizeBytes === $artifact->sizeBytes,
    'complete four-input Sites render provenance matches original generated bytes');
$sidecar = json_decode($rendered['provenance'],true,8,JSON_THROW_ON_ERROR);
$ok(count($sidecar) === 6 && $sidecar['planSha256']===$plan['planSha256'] &&
    $sidecar['artifact']===['sha256'=>$artifact->digest,'sizeBytes'=>$artifact->sizeBytes] &&
    $sidecar['authorityVerified']===false &&
    $sidecar['canPublish']===false &&
    $sidecar['canAcceptRealOrders']===false,
    'provenance keeps all three operational flags false and exact hashes');

$deny = static function(callable $run,string $label) use ($ok): void {
    try { $run(); }
    catch (RuntimeException $e) {
        $ok($e->getMessage()==='LOCAL_RENDER_DENIED' &&
            $e->getPrevious()===null,$label.' is refused by Sites');
        return;
    }
    $ok(false,$label.' was incorrectly accepted');
};
$wrong = Plan::build($snapshot,$editorial,$renderSelection,[
    'sha256'=>str_repeat('a',64),'sizeBytes'=>$artifact->sizeBytes,
]);
$deny(static fn()=>BriefRenderProvenance::render(
    $wrong['planBytes'],$snapshot['manifestBytes'],$source,$editorial),
    'declared digest that was not generated by the Sites renderer');
$otherSource = substr($source,0,-1)."\r\n";
$deny(static fn()=>BriefRenderProvenance::render(
    $plan['planBytes'],$snapshot['manifestBytes'],$otherSource,$editorial),
    'replacing rich briefing bytes after plan selection');
$anotherEditorial = substr($editorial,0,-1)."\r\n";
$deny(static fn()=>BriefRenderProvenance::render(
    $plan['planBytes'],$snapshot['manifestBytes'],$source,$anotherEditorial),
    'replacing editorial bytes after plan selection');

$next = Snapshot::build($contract,array_replace($selector,[
    'snapshotRef'=>'33333333-3333-4333-8333-333333333333',
    'sourceVersion'=>13,'expectedBriefRevision'=>1,
]),$source);
$deny(static fn()=>BriefRenderProvenance::render(
    $plan['planBytes'],$next['manifestBytes'],$next['sourceBytes'],$editorial),
    'a later snapshot cannot inherit the old render plan');
$ok($snapshot['authorityVerified']===false &&
    $plan['authorityVerified']===false &&
    $plan['clientAccepted']===false &&
    $plan['canPublish']===false &&
    $plan['canAcceptRealOrders']===false,
    'all candidate producer/render boundaries remain unprivileged');

echo "PORTAL-SITES PINNED RENDER PLAN PARITY PASS: {$checks} checks; no commercial authority.\n";
